#!/usr/bin/env python3
"""Prepare and report governed-repo hook experiments.

This helper automates the exact workflow needed for the read-gating observation
phase:

1. prepare one or more governed repos for a named experiment by archiving any
   existing hook log and writing a shell snippet that exports the required hook
   environment variables;
2. import the resulting `.claude/hook_log.jsonl` files into shared `llm_client`
   observability and print the friction summary plus variant comparison view.

The helper is intentionally small. It does not launch Claude Code or invent a
separate telemetry backend; it just removes the repetitive setup/reporting
steps that would otherwise make the observation phase tedious.
"""

from __future__ import annotations

import argparse
import importlib
import json
import shlex
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


@dataclass(frozen=True)
class ExperimentRepo:
    """Resolved governed repo plus the files used by experiment preparation."""

    root: Path
    hook_log: Path
    archive_dir: Path
    env_file: Path


def _timestamp_suffix() -> str:
    """Return one UTC timestamp suffix safe for filenames."""
    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def _slug(text: str) -> str:
    """Return a filesystem-safe slug without inventing hidden semantics."""
    normalized = "".join(
        ch if ch.isalnum() or ch in {"-", "_"} else "-" for ch in text.strip()
    )
    collapsed = "-".join(part for part in normalized.split("-") if part)
    if not collapsed:
        raise ValueError("experiment identifiers must contain at least one safe character")
    return collapsed


def _resolve_repo(repo_root_arg: str, *, experiment_id: str, variant_id: str) -> ExperimentRepo:
    """Resolve one repo root and fail loudly when the governed hook surface is absent."""
    repo_root = Path(repo_root_arg).expanduser().resolve()
    if not repo_root.exists():
        raise FileNotFoundError(f"repo root not found: {repo_root}")

    required_paths = [
        repo_root / ".claude" / "settings.json",
        repo_root / ".claude" / "hooks" / "gate-edit.sh",
        repo_root / ".claude" / "hooks" / "track-reads.sh",
        repo_root / "scripts" / "check_required_reading.py",
        repo_root / "scripts" / "meta" / "hook_log.py",
    ]
    for path in required_paths:
        if not path.exists():
            raise FileNotFoundError(
                f"governed repo experiment requires an active read-gating surface, missing: {path}"
            )

    experiment_slug = _slug(experiment_id)
    variant_slug = _slug(variant_id)
    hook_log = repo_root / ".claude" / "hook_log.jsonl"
    archive_dir = repo_root / ".claude" / "archive"
    env_file = repo_root / ".claude" / "experiments" / f"{experiment_slug}__{variant_slug}.env.sh"
    return ExperimentRepo(
        root=repo_root,
        hook_log=hook_log,
        archive_dir=archive_dir,
        env_file=env_file,
    )


def _env_file_content(*, experiment_id: str, variant_id: str) -> str:
    """Render one shell snippet that prepares a Claude session for the experiment."""
    experiment_quoted = shlex.quote(experiment_id)
    variant_quoted = shlex.quote(variant_id)
    return (
        "#!/bin/bash\n"
        "# Generated by scripts/governed_repo_experiment.py\n"
        f"export CLAUDE_HOOK_EXPERIMENT_ID={experiment_quoted}\n"
        f"export CLAUDE_HOOK_VARIANT_ID={variant_quoted}\n"
        'export CLAUDE_SESSION_READS_FILE=".claude/session_reads.${CLAUDE_HOOK_EXPERIMENT_ID}.$(date +%Y%m%d%H%M%S).txt"\n'
        "unset CLAUDE_HOOK_DOWNSTREAM_RUN_ID\n"
    )


def prepare_experiment(
    *,
    repo_roots: list[str],
    experiment_id: str,
    variant_id: str,
    archive_existing_log: bool = True,
) -> dict[str, Any]:
    """Archive current hook logs and write experiment env snippets for each repo."""
    if not repo_roots:
        raise ValueError("at least one --repo-root is required")

    repos = [
        _resolve_repo(repo_root, experiment_id=experiment_id, variant_id=variant_id)
        for repo_root in repo_roots
    ]
    archived_at = _timestamp_suffix()
    prepared: list[dict[str, Any]] = []

    for repo in repos:
        repo.root.joinpath(".claude", "experiments").mkdir(parents=True, exist_ok=True)
        archived_log: str | None = None
        if archive_existing_log and repo.hook_log.exists() and repo.hook_log.stat().st_size > 0:
            repo.archive_dir.mkdir(parents=True, exist_ok=True)
            archived_path = repo.archive_dir / f"hook_log.{archived_at}.jsonl"
            repo.hook_log.replace(archived_path)
            archived_log = str(archived_path.relative_to(repo.root))

        content = _env_file_content(experiment_id=experiment_id, variant_id=variant_id)
        repo.env_file.write_text(content, encoding="utf-8")
        repo.env_file.chmod(0o755)
        prepared.append(
            {
                "repo_root": str(repo.root),
                "repo_name": repo.root.name,
                "archived_log": archived_log,
                "env_file": str(repo.env_file.relative_to(repo.root)),
                "source_command": f"source {shlex.quote(str(repo.env_file.relative_to(repo.root)))}",
            }
        )

    return {
        "experiment_id": experiment_id,
        "variant_id": variant_id,
        "archive_existing_log": archive_existing_log,
        "prepared_repos": prepared,
    }


def report_experiment(
    *,
    repo_roots: list[str],
    experiment_id: str,
    days: int,
    limit: int,
) -> dict[str, Any]:
    """Import hook logs into shared observability and return the experiment report."""
    if not repo_roots:
        raise ValueError("at least one --repo-root is required")
    if days <= 0:
        raise ValueError("--days must be positive")
    if limit <= 0:
        raise ValueError("--limit must be positive")

    llm_client = importlib.import_module("llm_client")
    repos = [
        _resolve_repo(repo_root, experiment_id=experiment_id, variant_id="report")
        for repo_root in repo_roots
    ]

    imported: list[dict[str, Any]] = []
    summaries: list[dict[str, Any]] = []
    for repo in repos:
        if not repo.hook_log.exists():
            raise FileNotFoundError(f"hook log not found: {repo.hook_log}")
        imported_events = llm_client.import_governed_repo_hook_log(
            repo.hook_log,
            repo_name=repo.root.name,
        )
        imported.append(
            {
                "repo_name": repo.root.name,
                "repo_root": str(repo.root),
                "hook_log": str(repo.hook_log.relative_to(repo.root)),
                "imported_events": imported_events,
            }
        )
        summaries.append(
            llm_client.get_governed_repo_friction_summary(
                repo_name=repo.root.name,
                days=days,
                limit=limit,
            )
        )

    comparison = llm_client.get_governed_repo_variant_comparison(
        experiment_id=experiment_id,
        days=days,
    )
    return {
        "experiment_id": experiment_id,
        "days": days,
        "limit": limit,
        "imports": imported,
        "repo_summaries": summaries,
        "comparison": comparison,
    }


def _build_parser() -> argparse.ArgumentParser:
    """Return the CLI parser for experiment preparation and reporting."""
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)

    prepare_parser = subparsers.add_parser(
        "prepare", help="Archive logs and write per-repo experiment env files"
    )
    prepare_parser.add_argument("--repo-root", action="append", required=True, help="Repo root to prepare")
    prepare_parser.add_argument("--experiment-id", required=True, help="Stable experiment identifier")
    prepare_parser.add_argument("--variant-id", required=True, help="Stable variant identifier")
    prepare_parser.add_argument(
        "--no-archive-existing-log",
        action="store_true",
        help="Leave any existing .claude/hook_log.jsonl in place",
    )

    report_parser = subparsers.add_parser(
        "report",
        help="Import repo hook logs into llm_client observability and print summaries",
    )
    report_parser.add_argument("--repo-root", action="append", required=True, help="Repo root to report on")
    report_parser.add_argument("--experiment-id", required=True, help="Stable experiment identifier")
    report_parser.add_argument("--days", type=int, default=14, help="Rolling time window in days")
    report_parser.add_argument("--limit", type=int, default=10, help="Top-N limit for ranked outputs")

    return parser


def main(argv: list[str] | None = None) -> int:
    """Run the experiment helper and print deterministic JSON output."""
    parser = _build_parser()
    args = parser.parse_args(argv)

    if args.command == "prepare":
        payload = prepare_experiment(
            repo_roots=args.repo_root,
            experiment_id=args.experiment_id,
            variant_id=args.variant_id,
            archive_existing_log=not args.no_archive_existing_log,
        )
    else:
        payload = report_experiment(
            repo_roots=args.repo_root,
            experiment_id=args.experiment_id,
            days=args.days,
            limit=args.limit,
        )

    print(json.dumps(payload, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
